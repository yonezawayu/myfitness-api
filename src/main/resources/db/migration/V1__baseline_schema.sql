CREATE TABLE public.foods (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    calories_per_100g numeric(10,2) NOT NULL,
    carb_per_100g numeric(10,2) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    fat_per_100g numeric(10,2) NOT NULL,
    name character varying(255) NOT NULL,
    protein_per_100g numeric(10,2) NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT foods_pkey PRIMARY KEY (id)
);

CREATE TABLE public.meal_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    calories numeric(10,2) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    food_id bigint NOT NULL,
    meal_log_id bigint NOT NULL,
    protein numeric(10,2) NOT NULL,
    quantity_g numeric(10,2) NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT meal_items_pkey PRIMARY KEY (id)
);

CREATE TABLE public.meal_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    calories integer NOT NULL,
    date date NOT NULL,
    meal_name character varying(255) NOT NULL,
    memo character varying(255),
    protein double precision,
    CONSTRAINT meal_log_pkey PRIMARY KEY (id)
);

CREATE TABLE public.memo (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title character varying(255),
    CONSTRAINT memo_pkey PRIMARY KEY (id)
);

CREATE TABLE public.record (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    calories integer NOT NULL,
    date date,
    weight double precision NOT NULL,
    CONSTRAINT record_pkey PRIMARY KEY (id)
);

CREATE TABLE public.training_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    calories_burned integer,
    date date,
    training_name character varying(255),
    CONSTRAINT training_log_pkey PRIMARY KEY (id)
);

CREATE TABLE public.training_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    date date NOT NULL,
    memo character varying(500),
    CONSTRAINT training_sessions_pkey PRIMARY KEY (id)
);

CREATE TABLE public.training_exercises (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    exercise_name character varying(255) NOT NULL,
    memo character varying(500),
    training_session_id bigint NOT NULL,
    CONSTRAINT training_exercises_pkey PRIMARY KEY (id),
    CONSTRAINT fk_training_exercises_session
        FOREIGN KEY (training_session_id)
        REFERENCES public.training_sessions (id)
);

CREATE TABLE public.training_sets (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    memo character varying(500),
    reps integer NOT NULL,
    set_number integer NOT NULL,
    weight_kg numeric(10,2),
    training_exercise_id bigint NOT NULL,
    CONSTRAINT training_sets_pkey PRIMARY KEY (id),
    CONSTRAINT fk_training_sets_exercise
        FOREIGN KEY (training_exercise_id)
        REFERENCES public.training_exercises (id)
);

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    email character varying(255) NOT NULL,
    password_hash character varying(100) NOT NULL,
    role character varying(30) NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email)
);
