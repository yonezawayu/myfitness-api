    public.training_sessions,
    public.training_exercises,
    public.training_sets
TO myfitness_app;
GRANT USAGE, SELECT ON SEQUENCE
    public.users_id_seq,
    public.training_sessions_id_seq,
    public.training_exercises_id_seq,
    public.training_sets_id_seq
TO myfitness_app;
GRANT SELECT, INSERT ON TABLE public.training_session_creations TO myfitness_app;
GRANT USAGE, SELECT ON SEQUENCE public.training_session_creations_id_seq TO myfitness_app;
