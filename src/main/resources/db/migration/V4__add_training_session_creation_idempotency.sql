DO $$
BEGIN
    IF current_user <> 'myfitness_owner' THEN
        RAISE EXCEPTION 'V4 must run after SET ROLE myfitness_owner';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'myfitness_app') THEN
        RAISE EXCEPTION 'Required application role myfitness_app does not exist';
    END IF;
END
$$;

CREATE TABLE public.training_session_creations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    idempotency_key uuid NOT NULL,
    request_hash varchar(64) NOT NULL,
    training_session_id bigint,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT training_session_creations_pkey PRIMARY KEY (id),
    CONSTRAINT uk_training_session_creations_user_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT fk_training_session_creations_user
        FOREIGN KEY (user_id) REFERENCES public.users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_training_session_creations_session
        FOREIGN KEY (training_session_id) REFERENCES public.training_sessions (id) ON DELETE SET NULL
);

CREATE INDEX idx_training_session_creations_session
    ON public.training_session_creations (training_session_id);

REVOKE ALL ON TABLE public.training_session_creations FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.training_session_creations_id_seq FROM PUBLIC;
